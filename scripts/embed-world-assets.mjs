import { readdir, readFile, writeFile } from 'node:fs/promises';
import { basename, join } from 'node:path';

const textures = {};
for (const name of (await readdir('public/textures')).filter((file) => file.endsWith('.ktx2')).sort()) {
  textures[basename(name, '.ktx2')] = (await readFile(join('public/textures', name))).toString('base64');
}
if (!Object.keys(textures).length) throw new Error('No KTX2 textures to embed');
await writeFile('src/world/textureAssets.ts', `// Generated by scripts/embed-world-assets.mjs.\nexport const EMBEDDED_KTX2: Record<string, string> = ${JSON.stringify(textures)};\n`);
const image = (await readFile('public/images/meadow-preview.jpg')).toString('base64');
await writeFile('src/world/previewAsset.ts', `// Generated by scripts/embed-world-assets.mjs.\nexport const MEADOW_PREVIEW = 'data:image/jpeg;base64,${image}';\n`);
console.log(`Embedded ${Object.keys(textures).length} KTX2 textures and the meadow backdrop.`);